export function getProductBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getRelatedProducts(slug: string, limit = 4) {
  const product = getProductBySlug(slug);

  if (!product) {
    return [];
  }

  const sameFinish = products.filter((item) => item.slug !== slug && item.finish === product.finish);
  const otherProducts = products.filter((item) => item.slug !== slug && item.finish !== product.finish);

  return [...sameFinish, ...otherProducts].slice(0, limit);
}
